import react from '@vitejs/plugin-react';
import {defineConfig} from 'vite';
import type {Plugin} from 'vite';
import {existsSync, readFileSync, readdirSync} from 'node:fs';
import {join, sep} from 'node:path';

// The built app is committed and shipped with the repository, so the build writes
// dist/THIRD_PARTY_NOTICES.txt: every npm package that ends up in the bundle, its version, its
// licence field and its licence text. Licence comments are stripped from the bundle itself
// (the notices file carries them instead).
function thirdPartyNotices(): Plugin {
  const packages = new Map<string, string>(); // name -> package folder
  return {
    name: 'third-party-notices',
    apply: 'build',
    moduleParsed(info) {
      const id = info.id.replace(/\\/g, '/');
      const m = id.match(/\/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
      if (m) {
        const idx = id.lastIndexOf(`/node_modules/${m[1]}/`);
        packages.set(m[1], id.slice(0, idx + `/node_modules/${m[1]}`.length).split('/').join(sep));
      }
    },
    generateBundle() {
      const names = [...packages.keys()].sort();
      const parts = [
        'Third-party software bundled in this app (app/dist).',
        'Generated by app/vite.config.ts at build time. Each package keeps its own licence.',
        '',
      ];
      for (const name of names) {
        const dir = packages.get(name)!;
        let version = 'unknown';
        let license = 'unknown';
        try {
          const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
          version = pkg.version ?? version;
          license = typeof pkg.license === 'string' ? pkg.license : JSON.stringify(pkg.license ?? 'unknown');
        } catch {
          // keep the unknowns
        }
        const file = existsSync(dir)
          ? readdirSync(dir).find(f => /^(licen[cs]e|copying)(\.|$)/i.test(f))
          : undefined;
        const text = file ? readFileSync(join(dir, file), 'utf8').trim() : '(no licence file in the package)';
        parts.push('='.repeat(78), `${name} ${version}`, `License: ${license}`, '-'.repeat(78), text, '');
      }
      this.emitFile({type: 'asset', fileName: 'THIRD_PARTY_NOTICES.txt', source: parts.join('\n')});
    },
  };
}

// Escape every non-ASCII character in the emitted JavaScript and CSS as an escape sequence
// (\uXXXX in JavaScript, valid in strings, template literals, regular expressions and
// identifiers alike; \XXXXXX in CSS). The bundle then carries no typographic characters from
// third-party strings, and the repository's text checks pass without exemptions for it.
// generateBundle runs after minification, which would otherwise turn escapes back into the
// raw characters.
const NON_ASCII = /[^\u0000-\u007f]/g; // eslint-disable-line no-control-regex

function asciiOnly(): Plugin {
  return {
    name: 'ascii-only-output',
    apply: 'build',
    generateBundle(_options, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === 'chunk') {
          file.code = file.code.replace(NON_ASCII, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
        } else if (file.fileName.endsWith('.css') && typeof file.source === 'string') {
          file.source = file.source.replace(/[^\u0000-\u007f]/gu, c => '\\' + c.codePointAt(0)!.toString(16).padStart(6, '0')); // eslint-disable-line no-control-regex
        }
      }
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), thirdPartyNotices(), asciiOnly()],
  build: {
    outDir: 'dist',
    emptyOutDir: true,
    sourcemap: false,
    chunkSizeWarningLimit: 2000,
    rolldownOptions: {
      output: {
        comments: {legal: false},
      },
    },
  },
});
